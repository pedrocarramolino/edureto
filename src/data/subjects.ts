/** Subjects taught in a stage, in curriculum order. */
export function subjectsForStage(stage: Stage): Subject[] {
  return subjects.filter((subject) => subject.stages.includes(stage));
}

/**
 * Subjects whose id changed when the catalogue moved to the official
 * curriculum. Old saved games still carry the previous id.
 */
const legacyIds: Record<string, SubjectId> = {
  ciencias_naturales: "conocimiento_medio",
  ciencias_sociales: "conocimiento_medio",
};

export function getSubject(id: string) {
  return subjects.find((s) => s.id === id) ?? subjects.find((s) => s.id === legacyIds[id]);
}
